/** 文章の中に出てくる用語を、出現順に返す（記事の「この記事に出てくる用語」用） */
export function findTermsInText(text: string, limit = 5): GlossaryTerm[] {
  const hits: { t: GlossaryTerm; pos: number }[] = [];
  for (const t of GLOSSARY) {
    const key = t.term.replace(/（.*$/, "");
    const pos = text.indexOf(key);
    if (pos >= 0) hits.push({ t, pos });
  }
  return hits.sort((a, b) => a.pos - b.pos).slice(0, limit).map((h) => h.t);
}
